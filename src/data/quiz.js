const shuffle = (arr) => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

// 이번 판에서 이미 나온 문제 (방별 index 목록)
let history = {};
export const resetQuizHistory = () => { history = {}; };

/** 방에 맞는 문제 하나를 보기 섞어서 돌려준다. 이번 판에 안 나온 문제를 우선한다. */
export const pickQuiz = (stageId) => {
  const bank = QUIZ_BANK[stageId] || [];
  if (bank.length === 0) return null;
  const used = history[stageId] || [];
  let candidates = bank.map((_, i) => i).filter(i => !used.includes(i));
  if (candidates.length === 0) {
    history[stageId] = [];
    candidates = bank.map((_, i) => i);
  }
  const idx = candidates[Math.floor(Math.random() * candidates.length)];
  history[stageId] = [...(history[stageId] || []), idx];
  const base = bank[idx];
  return { ...base, answer: base.options[0], options: shuffle(base.options) };
};
