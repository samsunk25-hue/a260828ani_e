const shuffle = (arr) => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

/** 방에 맞는 문제 하나를 보기 섞어서 돌려준다 */
export const pickQuiz = (stageId) => {
  const bank = QUIZ_BANK[stageId] || [];
  if (bank.length === 0) return null;
  const base = bank[Math.floor(Math.random() * bank.length)];
  const answer = base.options[0];
  return { ...base, answer, options: shuffle(base.options) };
};
